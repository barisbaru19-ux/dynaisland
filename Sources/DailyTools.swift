// MARK: - Clipboard history

struct ClipItem: Identifiable {
    enum Content {
        case text(String)
        case image(NSImage)
    }

    let id = UUID()
    var content: Content
    var date: Date
}

/// Watches the general pasteboard (once a second) and records what you copy.
/// Kept in memory only. Items marked as passwords by password managers are skipped.
@MainActor
final class ClipboardMonitor {
    private let model: IslandModel
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int

    /// Markers that password managers and other apps put on private / temporary data.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    init(model: IslandModel) {
        self.model = model
        self.lastChange = NSPasteboard.general.changeCount
    }

    func tick() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard model.clipboardEnabled, change != model.ignoredPasteboardChange else { return }

        let types = pasteboard.types ?? []
        if types.contains(where: { ClipboardMonitor.privateTypes.contains($0) }) { return }
        if types.contains(.fileURL) { return }   // files copied in Finder

        if let text = pasteboard.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            model.recordClip(.text(text))
        } else if let image = NSImage(pasteboard: pasteboard) {
            model.recordClip(.image(image))
            // A picture with nothing else attached (no text, link or web page) is a screenshot
            // copied by Lightshot, CleanShot, ⌃⇧⌘4…: save it so it can be dragged from the shelf.
            let onlyImage = !types.contains(.html) && !types.contains(.URL) && !types.contains(.rtf)
            if onlyImage && model.autoShelfEnabled, let png = pngData() {
                saveScreenshot(png)
            }
        }
    }

    private func pngData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    /// Saves to Pictures/DynaIsland and puts the file on the shelf.
    private func saveScreenshot(_ png: Data) {
        let fm = FileManager.default
        let folder = fm.homeDirectoryForCurrentUser.appendingPathComponent("Pictures/DynaIsland", isDirectory: true)
        try? fm.createDirectory(at: folder, withIntermediateDirectories: true)
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd 'pukul' HH.mm.ss"
        let url = folder.appendingPathComponent("Screenshot \(formatter.string(from: Date())).png")
        guard (try? png.write(to: url)) != nil else { return }
        model.addToShelf([url])
        model.show(IslandNotice(symbol: "camera.viewfinder", title: "Screenshot", detail: "Shelf", tint: .white),
                   seconds: 2.2)
    }
}

// MARK: - Calendar (next meeting)

enum CalendarAccess: Equatable {
    case notDetermined, granted, denied
}

struct MeetingInfo: Identifiable, Equatable {
    let id: String
    var title: String
    var start: Date
    var end: Date
    var isAllDay: Bool
    var color: Color
    var location: String?
    var joinURL: URL?
}

/// Shown in the island from 10 minutes before a meeting until 5 minutes after it starts.
struct MeetingAlert: Equatable {
    var title: String
    var start: Date
    var isNow: Bool
    var key: String
    var joinURL: URL?
}

/// Reads today's and tomorrow's events from the Calendar app (iCloud, Google, Outlook…).
@MainActor
final class CalendarMonitor: NSObject {
    private let model: IslandModel
    private let store = EKEventStore()
    private var lastRefresh = Date.distantPast
    private var chimedKey = ""

    private static let meetingHosts = [
        "zoom.us", "meet.google.com", "teams.microsoft.com", "teams.live.com",
        "webex.com", "whereby.com", "meet.jit.si", "facetime.apple.com",
    ]

    init(model: IslandModel) {
        self.model = model
        super.init()
    }

    func start() {
        NotificationCenter.default.addObserver(self, selector: #selector(storeChanged),
                                               name: .EKEventStoreChanged, object: store)
        settingsChanged()
    }

    /// After launch or after the menu toggle: ask for access the first time, then read events.
    func settingsChanged() {
        updateAccess()
        if model.meetingEnabled && model.calendarAccess == .notDetermined && model.onboarded {
            requestAccess()
        } else {
            refresh()
        }
    }

    /// The "Izinkan" button: shows the system prompt, or System Settings if it was refused before.
    func requestAccess() {
        switch model.calendarAccess {
        case .granted:
            refresh()
        case .denied:
            if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Calendars") {
                NSWorkspace.shared.open(url)
            }
        case .notDetermined:
            Task { @MainActor in
                if #available(macOS 14.0, *) {
                    _ = try? await self.store.requestFullAccessToEvents()
                } else {
                    _ = try? await self.store.requestAccess(to: .event)
                }
                self.updateAccess()
                self.refresh()
            }
        }
    }

    /// Called once a second.
    func tick(now: Date = Date()) {
        if now.timeIntervalSince(lastRefresh) > 60 {
            updateAccess()   // picks up a permission granted in System Settings
            refresh()
        }
        guard model.meetingEnabled else {
            if model.meetingAlert != nil { model.meetingAlert = nil }
            return
        }

        var alert: MeetingAlert?
        for item in model.agenda where !item.isAllDay {
            let from = item.start.addingTimeInterval(-600)
            let until = min(item.start.addingTimeInterval(300), item.end)
            if now >= from && now < until {
                if item.id != model.dismissedMeetingKey {
                    alert = MeetingAlert(title: item.title, start: item.start, isNow: now >= item.start,
                                         key: item.id, joinURL: item.joinURL)
                }
                break
            }
        }

        if let alert = alert, alert.isNow, chimedKey != alert.key {
            chimedKey = alert.key
            NSSound(named: "Ping")?.play()
        }
        if model.meetingAlert != alert { model.meetingAlert = alert }
    }

    @objc private func storeChanged() {
        refresh()
    }

    private func updateAccess() {
        let status = EKEventStore.authorizationStatus(for: .event)
        let access: CalendarAccess
        if #available(macOS 14.0, *) {
            switch status {
            case .fullAccess: access = .granted
            case .notDetermined: access = .notDetermined
            default: access = .denied   // denied, restricted, write-only
            }
        } else {
            switch status {
            case .authorized: access = .granted
            case .notDetermined: access = .notDetermined
            default: access = .denied
            }
        }
        if model.calendarAccess != access { model.calendarAccess = access }
    }

    /// Re-reads the rest of today and tomorrow.
    private func refresh() {
        lastRefresh = Date()
        guard model.meetingEnabled, model.calendarAccess == .granted else {
            if !model.agenda.isEmpty { model.agenda = [] }
            return
        }

        let now = Date()
        let calendar = Calendar.current
        let startOfToday = calendar.startOfDay(for: now)
        guard let end = calendar.date(byAdding: .day, value: 2, to: startOfToday) else { return }
        let predicate = store.predicateForEvents(withStart: startOfToday, end: end, calendars: nil)

        var items: [MeetingInfo] = []
        for event in store.events(matching: predicate) {
            let startDate: Date? = event.startDate
            let endDate: Date? = event.endDate
            guard let start = startDate, let finish = endDate, finish > now,
                  event.status != .canceled, !CalendarMonitor.declined(event) else { continue }

            let rawTitle: String? = event.title
            let title = rawTitle?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            let identifier: String? = event.eventIdentifier
            let eventCalendar: EKCalendar? = event.calendar
            let nsColor: NSColor? = eventCalendar?.color

            items.append(MeetingInfo(
                id: "\(identifier ?? title)-\(Int(start.timeIntervalSince1970))",
                title: title.isEmpty ? "Tanpa judul" : title,
                start: start,
                end: finish,
                isAllDay: event.isAllDay,
                color: nsColor.map { Color(nsColor: $0) } ?? Color.white,
                location: event.location,
                joinURL: CalendarMonitor.joinURL(for: event)))
        }
        items.sort { $0.start < $1.start }
        if model.agenda != items { model.agenda = items }
    }

    private static func declined(_ event: EKEvent) -> Bool {
        guard let attendees = event.attendees else { return false }
        return attendees.contains { $0.isCurrentUser && $0.participantStatus == .declined }
    }

    /// A Zoom / Meet / Teams… link in the event's URL, location or notes.
    private static func joinURL(for event: EKEvent) -> URL? {
        if let url = event.url, isMeetingLink(url) { return url }
        let texts = [event.location, event.notes].compactMap { $0 }
        guard !texts.isEmpty,
              let detector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue) else { return nil }
        for text in texts {
            let range = NSRange(text.startIndex..., in: text)
            for match in detector.matches(in: text, options: [], range: range) {
                if let url = match.url, isMeetingLink(url) { return url }
            }
        }
        return nil
    }

    private static func isMeetingLink(_ url: URL) -> Bool {
        guard let host = url.host?.lowercased() else { return false }
        return meetingHosts.contains { host == $0 || host.hasSuffix("." + $0) }
    }
}

// MARK: - New downloads and screenshots → Shelf

/// Every 2 seconds, looks for new files in Downloads and the screenshot folder and puts them
/// on the shelf once they're complete. Listing runs off the main thread, so the macOS
/// "allow access to Downloads?" prompt never freezes the island.
enum WatchedKind: Sendable { case downloads, screenshots }

struct WatchedFolder: Sendable {
    let path: String
    let kind: WatchedKind
}

struct WatchedEntry: Sendable {
    let path: String
    let name: String
    let size: Int
    let isDirectory: Bool
    let isScreenCapture: Bool
}

struct FolderSnapshot: Sendable {
    let folder: WatchedFolder
    let entries: [WatchedEntry]?
}

@MainActor
final class FolderWatcher {
    private let model: IslandModel
    private var known: [String: Set<String>] = [:]   // folder path → names seen
    private var pending: [String: Int] = [:]           // file path → size at the last look
    private var lastScan = Date.distantPast
    private var scanning = false

    /// Still being written by a browser.
    private static let partialExtensions: Set<String> = ["crdownload", "download", "part", "partial", "opdownload", "tmp", "temp"]

    init(model: IslandModel) {
        self.model = model
    }

    /// Called once a second.
    func tick(now: Date = Date()) {
        guard now.timeIntervalSince(lastScan) >= 2, !scanning else { return }
        lastScan = now
        guard model.autoShelfEnabled, model.onboarded else {
            known.removeAll()
            pending.removeAll()
            return
        }

        scanning = true
        let folders = FolderWatcher.folders()
        Task.detached(priority: .utility) { [weak self] in
            let snapshots = folders.map { FolderWatcher.snapshot(of: $0) }
            await self?.apply(snapshots)
        }
    }

    private func apply(_ snapshots: [FolderSnapshot]) {
        scanning = false
        let readable = snapshots.allSatisfy { $0.entries != nil }
        if model.folderAccess != readable { model.folderAccess = readable }
        guard model.autoShelfEnabled else { return }
        for snapshot in snapshots {
            guard let entries = snapshot.entries else { continue }
            process(snapshot.folder, entries)
        }
    }

    private func process(_ folder: WatchedFolder, _ entries: [WatchedEntry]) {
        let names = Set(entries.map { $0.name })
        guard let seen = known[folder.path] else {
            known[folder.path] = names   // first look: everything already there is old
            return
        }
        known[folder.path] = names

        // Forget files that disappeared before they finished.
        for path in pending.keys where (path as NSString).deletingLastPathComponent == folder.path
            && !names.contains((path as NSString).lastPathComponent) {
            pending[path] = nil
        }

        for entry in entries where !seen.contains(entry.name) || pending[entry.path] != nil {
            consider(entry, in: folder, siblings: names)
        }
    }

    private func consider(_ entry: WatchedEntry, in folder: WatchedFolder, siblings: Set<String>) {
        let ext = (entry.name as NSString).pathExtension.lowercased()
        guard !entry.isDirectory, !FolderWatcher.partialExtensions.contains(ext) else {
            pending[entry.path] = nil
            return
        }
        // Firefox keeps an empty "file.pdf" next to "file.pdf.part" until it's done.
        let stillDownloading = ["part", "crdownload", "download"].contains { siblings.contains(entry.name + "." + $0) }
        if stillDownloading || entry.size == 0 {
            pending[entry.path] = -1
            return
        }
        if folder.kind == .screenshots && !entry.isScreenCapture {
            pending[entry.path] = nil   // some other file saved to the Desktop
            return
        }
        if pending[entry.path] == entry.size {
            pending[entry.path] = nil   // same size as 2 seconds ago: finished
            deliver(URL(fileURLWithPath: entry.path), kind: folder.kind)
        } else {
            pending[entry.path] = entry.size
        }
    }

    private func deliver(_ url: URL, kind: WatchedKind) {
        model.addToShelf([url])
        if Updater.isUpdateZip(url) {
            model.show(IslandNotice(symbol: "arrow.down.app.fill", title: "Update DynaIsland",
                                    detail: "Buka Shelf", tint: .green), seconds: 4)
            return
        }
        let ext = url.pathExtension.uppercased()
        switch kind {
        case .downloads:
            model.show(IslandNotice(symbol: "arrow.down.circle.fill", title: "Download selesai",
                                    detail: ext.isEmpty ? "File" : ext, tint: .green))
        case .screenshots:
            model.show(IslandNotice(symbol: "camera.viewfinder", title: "Screenshot",
                                    detail: "Shelf", tint: .white), seconds: 2.2)
        }
    }

    // MARK: Off the main thread

    private static func folders() -> [WatchedFolder] {
        let home = FileManager.default.homeDirectoryForCurrentUser
        let downloads = home.appendingPathComponent("Downloads", isDirectory: true).standardizedFileURL.path
        var result = [WatchedFolder(path: downloads, kind: .downloads)]
        let shots = screenshotFolder(home: home)
        if shots != downloads { result.append(WatchedFolder(path: shots, kind: .screenshots)) }
        return result
    }

    /// Where macOS saves screenshots (Screenshot app → Options → Save to), Desktop by default.
    private static func screenshotFolder(home: URL) -> String {
        if let saved = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location"), !saved.isEmpty {
            let expanded = (saved as NSString).expandingTildeInPath
            return URL(fileURLWithPath: expanded, isDirectory: true).standardizedFileURL.path
        }
        return home.appendingPathComponent("Desktop", isDirectory: true).standardizedFileURL.path
    }

    /// Reads Downloads and the Desktop once, which makes macOS ask for access. Off the main thread.
    nonisolated static func probeAccess() -> Bool {
        let home = FileManager.default.homeDirectoryForCurrentUser
        let downloads = try? FileManager.default.contentsOfDirectory(atPath: home.appendingPathComponent("Downloads").path)
        let desktop = try? FileManager.default.contentsOfDirectory(atPath: home.appendingPathComponent("Desktop").path)
        return downloads != nil && desktop != nil
    }

    nonisolated private static func snapshot(of folder: WatchedFolder) -> FolderSnapshot {
        let url = URL(fileURLWithPath: folder.path, isDirectory: true)
        let keys: [URLResourceKey] = [.fileSizeKey, .isDirectoryKey]
        guard let items = try? FileManager.default.contentsOfDirectory(at: url, includingPropertiesForKeys: keys,
                                                                        options: [.skipsHiddenFiles]) else {
            return FolderSnapshot(folder: folder, entries: nil)
        }
        let entries = items.map { item -> WatchedEntry in
            let values = try? item.resourceValues(forKeys: Set(keys))
            let isDirectory = values?.isDirectory ?? false
            return WatchedEntry(path: item.standardizedFileURL.path,
                         name: item.lastPathComponent,
                         size: values?.fileSize ?? 0,
                         isDirectory: isDirectory,
                         isScreenCapture: folder.kind == .screenshots && !isDirectory && isScreenCapture(item))
        }
        return FolderSnapshot(folder: folder, entries: entries)
    }

    /// Screenshots from macOS (tagged with an extended attribute) and from other apps
    /// such as Lightshot (any new picture saved to the screenshot folder).
    nonisolated private static func isScreenCapture(_ url: URL) -> Bool {
        let tagged = url.withUnsafeFileSystemRepresentation { path -> Bool in
            guard let path = path else { return false }
            return getxattr(path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) >= 0
        }
        if tagged { return true }
        // Fallback: the usual file names (English / Indonesian macOS).
        let name = url.lastPathComponent.lowercased()
        let prefixes = ["screenshot", "screen shot", "screen recording", "cuplikan layar", "tangkapan layar", "rekaman layar"]
        if prefixes.contains(where: { name.hasPrefix($0) }) { return true }
        let pictures: Set<String> = ["png", "jpg", "jpeg", "heic", "gif", "tiff", "webp", "bmp"]
        return pictures.contains(url.pathExtension.lowercased())
    }
}
